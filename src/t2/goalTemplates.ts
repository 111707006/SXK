/**
 * SMART 目標的九條模板（規格 v2 §8）。
 *
 * 【出處】
 * 舊原型 `files/sxk_t2_logic.js` 的 `GOALTPL`：九個維度各三欄（能力名稱、要練的事、做到的樣子）。
 * 這裡只留後兩欄 —— 能力名稱不是模板的內容，見下面「能力名稱不在這一檔」。
 * 規格說「沿用原型文字，改寫成家長用語後放進 `src/t2/goalTemplates.ts`」—— 這一檔就是那份改寫。
 *
 * 【改寫改了什麼】
 * 原型那三欄是寫給治療師看的：短期目標寫「于治疗情境中」、SEN 寫「减少过度反应」、
 * ATT 寫「抑制冲动」。客戶 2026-09-11 的《家长报告用语对照表》禁「治疗」，其餘幾句
 * 雖然沒有禁字，但都是「孩子身上有東西要壓下去」的寫法。改寫的原則與 `statusWording.ts`
 * 同一條：**缺陷框架換成發展框架**，練的事與做到的樣子一個都不減。
 *
 * 逐條的對照（左＝原型，右＝這裡）：
 *
 * | 維度 | 原型 | 這裡 | 為什麼 |
 * |---|---|---|---|
 * | COG | 两步骤问题解决 | 两步骤的动脑任务 | 「問題解決」是專業詞，家長讀不出要做什麼 |
 * | LANG | 在情境中用完整句表达需求 | 用完整句子说出需要 | 「表達需求」→ 家長話 |
 * | SOC | 主动发起互动 | 主动开启互动 | 同上 |
 * | EMO | 辨识情绪并使用调节策略 | 说出自己的心情，并用平静下来的方法 | 「策略」→ 家長話 |
 * | ATT | 维持专注并抑制冲动 | 保持专注，动作前先想一下 | 「抑制衝動」是把孩子講成要被壓制的 |
 * | MOT | 球类操作 | 球类 | 「操作」是治療室的詞 |
 * | SEN | 耐受并配合感觉活动，减少过度反应 | 参与各种感觉游戏，慢慢适应不喜欢的触感与声音 | 「耐受」「過度反應」是缺陷框架 |
 * | ADL | 独立完成穿脱、进食与清洁等自理流程 | 自己完成穿脱衣物、进食与清洁的日常流程 | 「獨立」「自理流程」→ 家長話 |
 * | LEARN | 读写与数概念 | 读写与数字概念 | 同上 |
 *
 * 【能力名稱不在這一檔】
 * 原型的第一欄自己取了名（「专注与执行」對正式站的「注意力与执行」、「理解与认知」對「认知」）。
 * 目標段落與九宮格講的是同一個維度，不該有第二種叫法（`src/utils/statusWording.ts` 檔頭記著
 * 這個專案發生過「同一顆紅燈五個名字」）。所以 `SmartGoal.area` 由 `dimensionMap.ts` 從正式站
 * 的 `DIMENSIONS_DATA` 查出來，這一檔不存名字。
 *
 * 【這一檔沒有的】
 * 沒有百分比、沒有週數、沒有孩子的名字 —— 那些是 `goals.ts` 依 `T2Findings` 填的。
 * 這裡只有「不隨孩子改變」的那三欄。
 */

import type { DimensionCode } from './types';

export interface GoalTemplate {
  /**
   * 要練的事。句子裡接在主詞後、「时」之前（「小明能在 12 周内，<activity>时，……」），
   * 所以自帶「在……中」這種介詞，句型不再加一個 —— 原型的 `于${act}时` 配上原型自己寫的
   * 「在情境中……」是「于在情境中……时」，兩個介詞疊在一起。
   */
  activity: string;
  /** 做到的樣子。放在長期目標句末的括號裡。 */
  criterion: string;
}


/**
 * 報告編號 —— 家長在電話上唸給客服聽的那一串（ADR-0007）。
 *
 * 【為什麼不是時間戳】
 * 2026-09-11 之前，報告抬頭寫的是 `SXK-{Date.now().toString().slice(-6)}`。那取的是
 * **渲染當下**的時間，不是報告的任何屬性：家長把同一份報告關掉重開，號碼就換了一個。
 * 客服拿著這個號碼找不到任何東西，家長也無法用它指認自己看的是哪一份。
 *
 * 【為什麼是雜湊而不是 id 的後六位】
 * 報告 id 的形狀是 `rec_<毫秒時間戳>`，取後六位等於「毫秒數對 100 萬取餘數」——
 * 每 16 分 40 秒繞回來一次。一位家長重測後再生成一份，兩份剛好同號是做得到的，
 * 而那正是這個號碼最需要分得開的情境。雜湊把整串 id 都吃進去，沒有這個週期。
 */

/**
 * FNV-1a（32 位元）。
 *
 * 選它不是為了安全性 —— 這個號碼不保護任何東西，它只是一個看得懂的標籤。
 * 選它是因為**兩行寫得完、不必引入相依、而且結果跨平台一致**：伺服器端與
 * 瀏覽器端都會算同一份報告的號碼，兩邊算出不同的值就等於這個號碼沒有用。
 *
 * `>>> 0` 是必要的：JS 的位元運算回傳有號 32 位元整數，少了它負數會讓
 * `toString(36)` 吐出一個帶減號的字串。
 */
function fnv1a(input: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < input.length; i++) {
    hash ^= input.charCodeAt(i);
    // 乘以 16777619，拆成位移是為了避開 32 位元以上的浮點數誤差。
    hash = (hash + ((hash << 1) + (hash << 4) + (hash << 7) + (hash << 8) + (hash << 24))) >>> 0;
  }
  return hash >>> 0;
}

/**
 * 由報告 id 算出這份報告的編號。同一個 id 永遠得到同一個號。
 *
 * 六碼 base36（約 21.7 億種）對這個規模綽綽有餘，而且唸得出來 —— 這串字會被
 * 家長對著電話唸給客服，不是被程式比對的。
 */
export function reportNumber(reportId: string): string {
  const code = fnv1a(reportId).toString(36).toUpperCase().padStart(6, '0').slice(-6);
  return `SXK-${code}`;
}

export function splitSentences(text: string): string[] {
  return text.split(/(?<=[。！？；])/).map(s => s.trim()).filter(Boolean);
}

/**
 * 給家長看的版本：逐句查表。踩到禁字又不在表上的句子**拿掉**（寧可少講一句，不放出禁字）——
 * 測試會擋住這種情形，所以正式資料上不會發生；這一層只是最後一道防線。
 */
export function adaptForParents(text: string): string {
  return splitSentences(text)
    .map(s => {
      if (Object.prototype.hasOwnProperty.call(REWRITES, s)) return REWRITES[s] ?? '';
      return findBannedWords(s).length === 0 ? s : '';
    })
    .join('');
}

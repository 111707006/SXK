/**
 * 內含禁字、卻**不是在講孩子**的句子，原文保留，掃描時跳過。
 *
 * 清單是死的，判斷是活的：禁字擋的是「把孩子說成有病」，不是那幾個字本身。
 * 「网络连接异常」的「异常」說的是連線；「正常偏低音」的「偏低」說的是音量。
 * 為了讓掃描通過而把這種句子改掉，是讓工具替人做判斷 —— 2026-09-11 犯過一次，
 * 使用者指出來了。新的例外加在這裡，附一句它為什麼不是在講孩子。
 */
export const ALLOWED_PHRASES: ReadonlyArray<string> = [
  // 對照表指定的定位句：「不是诊断」是在否定它，不是在用它。
  '本报告为发展筛查，用于发现需要进一步了解的方面，不是诊断。',
  // 網路錯誤訊息，說的是連線。
  '网络应答异常',
  '网络连接异常',
  // 朗讀練習的音量，說的是聲音。
  '正常偏低音',
];

/** 回傳 `text` 裡出現的每一個禁字，附上前後文，方便一眼看出是哪一句。 */
export function findBannedWords(text: string): string[] {
  let scrubbed = text;
  for (const phrase of ALLOWED_PHRASES) scrubbed = scrubbed.split(phrase).join('');

  const hits: string[] = [];
  for (const word of BANNED_WORDS) {
    let from = 0;
    while (true) {
      const at = scrubbed.indexOf(word, from);
      if (at < 0) break;
      const ctx = scrubbed.slice(Math.max(0, at - 18), at + word.length + 18).replace(/\s+/g, ' ');
      hits.push(`「${word}」 …${ctx}…`);
      from = at + word.length;
    }
  }
  return hits;
}

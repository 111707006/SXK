export interface CpmvItem {
  id: number;
  mod: string;          // module key A-E
  name: string;
  age: string;          // reference age band
  bi?: boolean;         // bilateral (test both sides, score the worse side)
  cmd: string;          // instruction to the child
  film: string;         // filming guidance
  watch: string;        // observation points
  ai: string;           // AI capture metrics
  s2: string;           // scoring anchor for 2 (good)
  s1: string;           // scoring anchor for 1 (abnormal quality)
  s0: string;           // scoring anchor for 0 (cannot do)
}

export interface CpmvFlag {
  k: string;
  label: string;
  side?: boolean;       // laterality flag (left/right worse)
}

export interface CpmvDomain {
  key: string;
  name: string;
  items: number[];      // item ids belonging to this domain
}


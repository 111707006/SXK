-- 偏移规则等于没有。**NULL 的活动配不到**（§7.4），后台要把「300 支已填 N 支」
-- 显示成进度数字。
--
-- 【种子从哪里来】
-- 旧原型的 ACT300（files/sxk_t2_activities.js）：300 个名称与适龄字串。
-- 由 scripts/t2-extract-act300.ts 抽成 src/t2/act300.ts，再由 src/t2/activitySeed.ts
-- 算出模组、月龄区间、维度初值（附录 B.3），最后由 scripts/t2-activity-seed-sql.ts
-- 印成底下标记之间的 INSERT。**标记之间的区段不要手改**，test/activitySeed.test.ts
-- 会重印一次比对。
--
-- 【只有专案 A 需要】

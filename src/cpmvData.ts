export function cpmvGrade(pct: number): { t: string; c: string } {
  if (pct >= 85) return { t: '功能良好 / 轻微受限', c: '#2E7D32' };
  if (pct >= 60) return { t: '轻–中度受限', c: '#C07600' };
  if (pct >= 35) return { t: '中度受限', c: '#C05621' };
  return { t: '重度受限', c: '#B3402E' };
}
